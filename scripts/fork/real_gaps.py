"""Fork-only. List the translations that are really incomplete (nv-rs#930).

Each `// Translation incomplete: <address> - <why>` marker says a translation leaves something out.
Most say only that the C++ exception frame (`FS:[0]`, SEH, a funclet or filter) or the `/GS` cookie
check is not translated: the ordinary path is complete. The others mark a real gap: an x87 status
word, an uninitialised stack read, a register-only entry or a write past a frame. Those addresses
are the ones the decomp backend stands in for when it is built (`typed/backend_gaps.rs`).

Run: python3 -I scripts/fork/real_gaps.py --root . [--check]

Without `--check` it writes `crates/engine-core/src/typed/real_gaps.txt`, one `<address> <file> <eax|registers>` line
per real gap. It reads source comments only, never game data. The exception-only markers are counted
and not listed.
"""
import argparse
import re
import sys
from pathlib import Path

MARKER = re.compile(r"^\s*//\s*Translation incomplete: ([0-9a-fA-F]{8}) - (.*)$")
COMMENT = re.compile(r"^\s*//(?!/)\s?(.*)$")
EXCEPTION_ONLY = re.compile(
    r"FS:|exception|\bSEH\b|cookie|unwind|/GS|funclet|__except|__finally|filter|handler",
    re.IGNORECASE,
)
OUTPUT = Path("crates/engine-core/src/typed/real_gaps.txt")
HEADER = (
    "# Generated by scripts/fork/real_gaps.py (nv-rs#930): translations marked incomplete for a\n"
    "# reason other than the exception frame or the /GS cookie. `<address> <file> <result>`: `eax` when\n"
    "# the backend's one-word result is all a caller reads, `registers` when not (stays on the translation).\n"
    "# Do not edit; run python3 -I scripts/fork/real_gaps.py --root .\n"
)


# A reason that names one of these leaves something out besides the frame, whatever else it says.
REAL_GAP = re.compile(
    r"uninitiali[sz]ed|x87|status word|FSTSW|FNSTSW|FPREM|MXCSR|register input|not registered|"
    r"stale|never written|never writes|unwritten|past (?:its|the)|writes? past|garbage|"
    r"leaves? .* unwritten|read before (?:they are|it is) written|whatever (?:register|the stack)|"
    r"previous value of E[A-Z]{2}|machine state the engine does not have",
    re.IGNORECASE,
)

# What the backend's export cannot hand back, from the marker. The export returns one word (EAX, or
# an f32): a gap whose caller reads EDX, ST0 or an x87/SSE status, or whose function takes or
# leaves register state (register inputs, a register-only entry, a stale register or XMM lane),
# stays on its translation.
REGISTER_STATE = re.compile(
    r"x87|status word|FSTSW|FNSTSW|FPREM|FSQRT|MXCSR|XMM|\bST0\b|\bEDX\b|register input|"
    r"register-only|stale (?:E[A-Z]{2}|register)|left over from an? (?:earlier )?(?:E[A-Z]{2}|XMM)|"
    r"machine state the engine does not have",
    re.IGNORECASE,
)
# What the translation's own source says it returns: a wide result (`u64` is EAX and EDX, `f64` is
# ST0), an explicit `Ret`, or an `edx:`/`st0:` field of one. A local named `edx`, or a callee's `.st0` that is read, is not.
REGISTER_BODY = re.compile(r"->\s*(?:u64|i64|f64|Ret)\b|\bRet\s*\{|\b(?:edx|st0)\s*:\s*[^=]")


def is_exception_only(text):
    """True when the frame or the /GS check is the only thing the reason says is left out."""
    return bool(EXCEPTION_ONLY.search(text)) and not REAL_GAP.search(text)


def one_word(reason, body):
    """True when the backend's one-word result is everything a caller can read from the gap."""
    return not REGISTER_STATE.search(reason) and not REGISTER_BODY.search(body)


def function_body(lines, start):
    """The source of the function the comments from `start` on introduce: from its `fn` line to the
    closing brace in column 0 (or the next marker when the file has none)."""
    out = []
    started = False
    for line in lines[start:]:
        if not started:
            if re.match(r"^\s*(?:pub(?:\([a-z]+\))?\s+)?(?:unsafe\s+)?fn\s", line):
                started = True
            elif MARKER.match(line):
                break
            else:
                continue
        out.append(line)
        if line.startswith("}"):
            break
    return "\n".join(out)


def markers(path, text):
    """Yield (address, reason) for each marker in `text`, the reason running over the comment
    lines that continue it."""
    for address, reason, _ in translations(text):
        yield address, reason


def translations(text):
    """Yield (address, reason, body) for each marker: the reason running over the comment lines
    that continue it, and the source of the function it introduces."""
    lines = text.splitlines()
    for i, line in enumerate(lines):
        found = MARKER.match(line)
        if not found:
            continue
        reason = [found.group(2)]
        for nxt in lines[i + 1:]:
            more = COMMENT.match(nxt)
            if not more or MARKER.match(nxt):
                break
            reason.append(more.group(1))
        yield found.group(1).lower(), " ".join(reason), function_body(lines, i + 1)


def scan(root):
    """Map each real-gap address to (source file, whether a one-word result covers it); also count
    the exception-only addresses. A gap with several markers is one-word only when all are."""
    gaps, exception_only = {}, set()
    for path in sorted((root / "crates").rglob("*.rs")):
        if "target" in path.relative_to(root).parts:
            continue
        text = path.read_text(encoding="utf-8", errors="replace")
        for address, reason, body in translations(text):
            if is_exception_only(reason):
                exception_only.add(address)
            else:
                file, word = gaps.get(address, (path.relative_to(root).as_posix(), True))
                gaps[address] = (file, word and one_word(reason, body))
    return gaps, exception_only - set(gaps)


def render(gaps):
    return HEADER + "".join(
        "%s %s %s\n" % (a, gaps[a][0], "eax" if gaps[a][1] else "registers") for a in sorted(gaps)
    )


def parse(text):
    """The addresses in a generated list."""
    out = []
    for line in text.splitlines():
        line = line.split("#")[0].strip()
        if line:
            out.append(int(line.split()[0], 16))
    return out


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--root", default=".")
    ap.add_argument("--check", action="store_true", help="fail when the committed list is stale")
    args = ap.parse_args(argv)
    root = Path(args.root)
    gaps, exception_only = scan(root)
    text = render(gaps)
    target = root / OUTPUT
    print("real gaps: %d, exception-only: %d" % (len(gaps), len(exception_only)))
    if args.check:
        if not target.is_file() or target.read_text(encoding="utf-8") != text:
            print("stale: run python3 -I scripts/fork/real_gaps.py --root .", file=sys.stderr)
            return 1
        return 0
    target.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
